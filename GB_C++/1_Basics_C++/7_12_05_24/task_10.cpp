/** Кофемашина
Что нужно сделать
Инженеры компании «Спейс Инжиниринг» не могут продуктивно работать без кофе. 
Недавно в их кофемашину случайно попал космический луч и повредил программу-прошивку. Вас умоляют помочь. 
Кофемашина умеет готовить два напитка: американо и латте. Для американо требуется 300 мл воды, 
а для латте 30 мл воды и 270 мл молока.

Напишите программу, которая спрашивает у пользователя 
(это действие программа делает один раз в начале работы), сколько всего миллилитров молока и воды залито 
в кофемашину, после чего начинает обслуживание, спрашивая, какой напиток хочет очередной посетитель. 
Пользователь выбирает один из двух напитков, программа отвечает одним из трёх вариантов: 
«Ваш напиток готов», «Не хватает воды» или «Не хватает молока», 
после чего переходит к обслуживанию следующего посетителя. 
Если молока и воды не хватает ни на один вид напитка, программа выдаёт отчёт и завершается. 
В отчёте должно быть написано, что ингредиенты подошли к концу, должен быть указан остаток воды и молока 
в машине, а также должно быть указано, сколько всего было приготовлено чашек американо и латте за эту смену. Выберите наиболее удобный для написания программы цикл. Обеспечьте контроль ввода.

Пример выполнения

Введите количество воды в мл: 30
Введите количество молока в мл: 270
Выберите напиток (1 — американо, 2 — латте): 2
Ваш напиток готов.
***Отчёт***
Ингредиентов осталось:
Вода: 0 мл
Молоко: 0 мл
Кружек американо приготовлено: 0
Кружек латте приготовлено: 1

Рекомендации по выполнению
• Перед тем как останавливать работу кофемашины, нужно убедиться, что ни один из напитков нельзя приготовить.
• Количество напитков разных видов следует считать отдельно.
• Для решения программы рекомендуется использовать цикл while.

Что оценивается
• Правильно определяется количество оставшихся ингредиентов.
• Количество ингредиентов не становится отрицательным.
• Программа не выводит отчёт, если количества ингредиентов хватает хотя бы на один из напитков.
• Если ингредиентов не хватает для приготовления любого из напитков, программа должна вывести отчёт.*/

#include <iostream>
#include <string>

using namespace std;

class task_10
{
    public:
        void coffee_machine()
        {
            int water, milk;
            cout << "Enter the amount of water in ml: ";
            cin >> water;
            cout << "Enter the amount of milk in ml: ";
            cin >> milk;
            int americano = 0, latte = 0;
            while (true)
            {
                cout << "Select a drink (1 - americano, 2 - latte): ";
                int drink;
                cin >> drink;
                if (drink == 1)
                {
                    if (water >= 300)
                    {
                        cout << "Your drink is ready.\n";
                        water -= 300;
                        americano++;
                    }
                    else
                    {
                        cout << "Not enough water.\n";
                    }
                }
                else if (drink == 2)
                {
                    if (water >= 30 && milk >= 270)
                    {
                        cout << "Your drink is ready.\n";
                        water -= 30;
                        milk -= 270;
                        latte++;
                    }
                    else
                    {
                        cout << "Not enough water or milk.\n";
                    }
                }
                else
                {
                    cout << "Incorrect input.\n";
                }
                if (water < 30 && milk < 270)
                {
                    cout << "***Report***\n";
                    cout << "Ingredients left:\n";
                    cout << "Water: " << water << " ml\n";
                    cout << "Milk: " << milk << " ml\n";
                    cout << "Cups of americano made: " << americano << endl;
                    cout << "Cups of latte made: " << latte << endl;
                    break;
                }
            }
            cin.ignore(32767, '\n');
        }
};