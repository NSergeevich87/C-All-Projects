/** Immolate Improved!
Что нужно сделать
Мы придумываем фэнтезийную онлайн-игру в жанре RPG. В орка стреляют огненными шарами разной степени мощности, 
но у него есть очки здоровья и показатель сопротивляемости магии. Очки здоровья, сопротивляемость магии и 
мощность огненного шара — это вещественные числа от нуля до единицы включительно. Чем больше мощность, 
тем больше урон здоровью, но чем больше сопротивляемость магии, тем урон меньше. Например, если 
сопротивляемость равна нулю (0%), то будет нанесён урон, равный мощности огненного шара. 
Если сопротивляемость равна единице (100%), урон будет равен нулю, даже если мощность заклинания максимальна.

Напишите программу, в которой пользователь сначала задаёт количество здоровья и сопротивляемость магии орка, 
а после стреляет в него огненными шарами разной мощности, пока орк не погибнет. Мощность удара вводится с 
клавиатуры с каждым выстрелом. После каждого заклинания программа выводит на экран итоговый урон от удара и 
оставшиеся очки здоровья орка. Показатель сопротивляемости магии не изменяется при попадании. 
Обеспечьте контроль ввода.

Обратите внимание, что сопротивляемость обозначает только долю от повреждения, которая приходится на орка. 
Пример:
Урон 0.1, сопротивляемость 0.5, по орку будет нанесено 0.05 урона;
Урон 0.2, сопротивляемость 0.5, по орку будет нанесено 0.1 урона;
Урон 1, сопротивляемость 0.2, по орку будет нанесено 0.8 урона.

Рекомендации по выполнению
Для решения использовать цикл while.

Что оценивается
Все величины должны измеряться в одной шкале — от 0 до 1.
Мощность удара считается с учётом сопротивляемости.*/

#include <iostream>
#include <string>

using namespace std;

class task_13
{
    public:
        void run()
        {
            cout << "Enter the health of the orc: ";
            string health;
            getline(cin, health);
            float health_f = stof(health);
            if (health_f < 0 || health_f > 1)
            {
                cout << "Invalid input." << endl;
                return;
            }

            cout << "Enter the magic resistance of the orc: ";
            string resistance;
            getline(cin, resistance);
            float resistance_f = stof(resistance);
            if (resistance_f < 0 || resistance_f > 1)
            {
                cout << "Invalid input." << endl;
                return;
            }

            while (health_f > 0)
            {
                cout << "Enter the power of the fireball: ";
                string power;
                getline(cin, power);
                float power_f = stof(power);
                if (power_f < 0 || power_f > 1)
                {
                    cout << "Invalid input." << endl;
                    continue;
                }

                float damage = power_f * (1 - resistance_f);
                health_f -= damage;
                if (health_f < 0)
                {
                    health_f = 0;
                }
                cout << "Damage: " << damage << ", remaining health: " << health_f << endl;
            }
        }
};