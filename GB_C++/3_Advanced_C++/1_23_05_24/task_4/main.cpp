/** Задание 4. Разработка детектора PNG-файла
Что нужно сделать
Разработайте программу, которая получает на вход, в стандартный ввод, путь к файлу. На выходе программа 
должна определить, является ли данный файл PNG-изображением. Данная процедура не просто должна смотреть на 
расширение файла, но и произвести минимальный анализ его внутренностей, в бинарном режиме.
Внутренности валидного бинарного файла начинаются со специального 8-байтового заголовка. Нас будут 
интересовать первые четыре байта. Первый байт всегда имеет значение −119 (число со знаком минус), а 
следующие — это просто символы ‘P’, ‘N’, ‘G’, расположенные друг за другом. Обратите внимание, что все 
они в верхнем регистре.
По результатам проверки пути и внутренностей требуется сообщить пользователю о результате проверки в 
стандартный вывод.

Советы и рекомендации
Чтобы определить расширение файла, используйте функцию substr, которая получает офсет и длину подстроки 
и возвращает её.*/

#include <iostream>
#include <fstream>
#include <string>

using namespace std;

bool isPng(string path)
{
    ifstream file(path, ios::binary);
    if (!file.is_open())
    {
        cout << "Error opening file" << endl;
        return false;
    }

    char buffer[4];
    file.read(buffer, 4);
    file.close();

    return buffer[0] == -119 && buffer[1] == 'P' && buffer[2] == 'N' && buffer[3] == 'G';
}

int main()
{
    string path;
    cout << "Enter the path to the file: ";
    cin >> path;

    if (isPng(path))
    {
        cout << "This is a PNG file" << endl;
    }
    else
    {
        cout << "This is not a PNG file" << endl;
    }

    return 0;
}