/** Задание 2. Игра по ловле рыбы
Что нужно сделать
Реализуйте простую игру-симуляцию ловли рыбы. Игровое поле представляет собой девять секторов условного пруда. 
В начале игры в одном из этих секторов с помощью генератора случайных чисел оказывается рыба. 
Точно так же, случайным образом, по секторам пруда распределяются и три сапога. Сапог и рыба при этом не могут 
находиться в одном и том же секторе одновременно, как и несколько сапог сразу в одном из секторов.
Игрок закидывает удочку с приманкой в один из секторов, номер которого вводится стандартным способом через консоль. 
Задача игрока — угадать сектор, в котором находится рыба и, таким образом, поймать её. Если игрок попал на 
пустой сектор, то удочку надо забросить повторно. Если игрок поймал сапог, то игра завершается с отрицательным 
результатом.
Реализовать задачу нужно с помощью исключений: когда успешный заброс удочки генерирует специальное 
пользовательское исключение, после чего программа должна завершиться и оповестить пользователя об успешной 
рыбалке и количестве попыток, которое ему для этого потребовалось. Если же был пойман сапог, 
то должно выводиться сообщение о неудачной ловле
.
Рекомендации
Вспомните, что вы можете выбросить в качестве исключения произвольный тип данных. Это может быть и сапог, и рыба.
В функции main потребуется расположить рыбу случайным образом. Для этого сделайте std::srand(std::time(nullptr));
а затем само расположение: field[std::rand() % 9].fish = new Fish(); Благодаря оператору % вы не выйдете 
за пределы массива. */

#include <iostream>
#include <ctime>
#include <cstdlib>

class Fish
{
};

class Boot
{
};

class Sector
{
public:
    Fish *fish = nullptr;
    Boot *boot = nullptr;
};

class Pond
{
public:
    Pond()
    {
        for (int i = 0; i < 3; ++i)
        {
            field[std::rand() % 9].boot = new Boot();
        }
        field[std::rand() % 9].fish = new Fish();
    }

    void throw_fishing_rod(int sector)
    {
        if (field[sector].fish)
        {
            throw Fish();
        }
        if (field[sector].boot)
        {
            throw Boot();
        }
    }

private:
    Sector field[9];
};

int main()
{
    std::srand(std::time(nullptr));
    Pond pond;
    int sector;
    int attempts = 0;
    while (true)
    {
        std::cout << "Enter sector number: ";
        std::cin >> sector;
        try
        {
            pond.throw_fishing_rod(sector);
            std::cout << "You caught a fish!" << std::endl;
            std::cout << "Attempts: " << attempts << std::endl;
            break;
        }
        catch (Fish &)
        {
            std::cout << "You caught a boot!" << std::endl;
            break;
        }
        catch (Boot &)
        {
            std::cout << "You caught a boot!" << std::endl;
            break;
        }
        ++attempts;
    }
    return 0;
}