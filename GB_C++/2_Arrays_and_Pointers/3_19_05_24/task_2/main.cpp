/** Задание 2. Крестики-нолики
Что нужно сделать
Старая добрая игра на страницах всех школьных тетрадей. Поле размером 3 × 3 представлено в виде двумерного 
массива с типом элементов char. Участвуют два игрока, они ходят по очереди и ставят в указанные ими в 
стандартном вводе координаты свой символ — X или O (буквы латинского алфавита). Как только у одного из 
игроков будет установлено подряд три крестика или три нолика, он побеждает. Если свободных клеток не 
осталось, а трёх совпадающих элементов не найдено, то объявляется ничья. Для простоты не будем рассматривать 
диагональные совпадения — только строго вертикальные и строго горизонтальные.
Изначально всё поле инициализируется символом пробела — ‘ ‘(для обозначения пробела кавычки одинарные и в 
одну сторону). Это можно сделать сразу при объявлении либо с помощью вложенного цикла. На каждом ходе при 
занятой клетке или при неверных координатах этой клетки должно быть выведено сообщение, и игрок должен 
указать координаты клетки повторно. После каждого хода надо выводить в консоль текущее состояние всего 
игрового поля для наглядности.*/

#include <iostream>
#include <iomanip>

using namespace std;

int main()
{
    const int size = 3;
    char field[size][size] = {{' ', ' ', ' '}, {' ', ' ', ' '}, {' ', ' ', ' '}};

    int x, y;
    char player = 'X';
    bool win = false;

    while (!win)
    {
        cout << "Enter the coordinates for the player " << player << " (x, y): ";
        cin >> x >> y;

        if (x < 0 || x >= size || y < 0 || y >= size || field[x][y] != ' ')
        {
            cout << "Invalid coordinates. Try again." << endl;
            continue;
        }

        field[x][y] = player;

        for (int i = 0; i < size; i++)
        {
            if (field[i][0] == player && field[i][1] == player && field[i][2] == player)
            {
                win = true;
                break;
            }
            if (field[0][i] == player && field[1][i] == player && field[2][i] == player)
            {
                win = true;
                break;
            }
        }

        cout << "Current field:" << endl;
        for (int i = 0; i < size; i++)
        {
            for (int j = 0; j < size; j++)
            {
                cout << setw(3) << field[i][j];
            }
            cout << endl;
        }

        if (win)
        {
            cout << "Player " << player << " wins!" << endl;
        }
        else
        {
            player = player == 'X' ? 'O' : 'X';
        }
    }

    return 0;
}