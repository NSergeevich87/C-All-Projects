/** Задание 1. Банкетный стол
Что нужно сделать
По поводу успешного прохождения двумерных массивов собирается банкет, организуется стол на 12 персон. 
Есть два VIP-места, они рядом во главе стола. Стол протяжён в длину, места расположены в два ряда. 
Каждый пришедший должен быть «упакован» соответствующим образом. Во-первых, столовые приборы: 
по три на каждого человека (вилка, ложка, нож) и одна маленькая дополнительная ложечка для VIP-персон 
(для десерта). Во-вторых, тарелки: каждому по две (для первого и второго блюда) и ещё одна тарелка для 
VIP-персон (для десерта). В-третьих, стулья: минимум один для каждого гостя. Заведите соответствующие 
двумерные массивы для количества приборов, посуды и стульев и проинициализируйте их.
Но это ещё не всё. На банкете после инициализации происходят некоторые события. 
Пришедшая на пятое место первого ряда дама привела с собой ребёнка, и поэтому на данное место был 
приставлен ещё один стул. С третьего места во втором ряду в неизвестном направлении была украдена ложка. 
Одна из VIP-персон (любая) поделилась своей ложкой с тем, кто остался без ложки, и стала есть суп десертной. 
За ненадобностью официант забрал у VIP-гостя одну десертную тарелку, ведь есть десерт ложкой, которая уже 
побывала уже в супе, неприлично. Больше без происшествий, однако эти события на банкете надо отразить в 
инициализированных ранее массивах.*/

#include <iostream>
#include <iomanip>

using namespace std;

int main()
{
    const int guests = 12;
    const int vip = 2;
    const int cutlery = 3;
    const int plates = 2;
    const int chairs = 1;

    int cutleryArr[guests][cutlery] = {0};
    int platesArr[guests][plates] = {0};
    int chairsArr[guests] = {0};

    for (int i = 0; i < guests; i++)
    {
        for (int j = 0; j < cutlery; j++)
        {
            cutleryArr[i][j] = 1;
        }
        for (int j = 0; j < plates; j++)
        {
            platesArr[i][j] = 1;
        }
        chairsArr[i] = 1;
    }

    // Пришедшая на пятое место первого ряда дама привела с собой ребёнка, и поэтому на данное место был приставлен ещё один стул.
    chairsArr[4]++;

    // С третьего места во втором ряду в неизвестном направлении была украдена ложка.
    cutleryArr[1][1] = 0;

    // Одна из VIP-персон (любая) поделилась своей ложкой с тем, кто остался без ложки, и стала есть суп десертной.
    for (int i = 0; i < guests; i++)
    {
        if (cutleryArr[i][1] == 0)
        {
            cutleryArr[i][1] = 1;
            break;
        }
    }

    // За ненадобностью официант забрал у VIP-гостя одну десертную тарелку, ведь есть десерт ложкой, которая уже побывала уже в супе, неприлично.
    for (int i = 0; i < guests; i++)
    {
        if (platesArr[i][1] == 1)
        {
            platesArr[i][1] = 0;
            break;
        }
    }

    cout << "Cutlery:" << endl;
    for (int i = 0; i < guests; i++)
    {
        cout << setw(2) << i + 1 << ": ";
        for (int j = 0; j < cutlery; j++)
        {
            cout << cutleryArr[i][j] << " ";
        }
        cout << endl;
    }

    cout << "Plates:" << endl;
    for (int i = 0; i < guests; i++)
    {
        cout << setw(2) << i + 1 << ": ";
        for (int j = 0; j < plates; j++)
        {
            cout << platesArr[i][j] << " ";
        }
        cout << endl;
    }

    cout << "Chairs:" << endl;
    for (int i = 0; i < guests; i++)
    {
        cout << setw(2) << i + 1 << ": " << chairsArr[i] << endl;
    }

    return 0;
}